"""Render the seed catalog as a Lean building instantiation.

``load_catalog`` is the only read of the catalog. ``--check`` compares the
committed file and does not write.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Callable
from pathlib import Path

from pattern_language.catalog import Catalog, CatalogLoadError, Pattern, load_catalog

REPO_ROOT = Path(__file__).resolve().parents[1]
BUILDINGS_RELATIVE = Path("lean") / "PatternLanguage" / "Instantiations" / "Buildings.lean"
STALE = "stale: lean/PatternLanguage/Instantiations/Buildings.lean"
_SCALES = frozenset({"town", "building", "construction"})


def render(catalog: Catalog) -> str:
    """Render ``catalog.patterns`` as ``Instantiations/Buildings.lean``."""
    patterns = tuple(sorted(catalog.patterns, key=lambda item: item.number))
    lines = [
        "-- Generated by scripts/catalog_to_lean.py. Do not edit.",
        "import PatternLanguage.Language",
        "import PatternLanguage.Sequence",
        "",
        "namespace PatternLanguage.Instantiations.Buildings",
        "",
        *_inductive(patterns),
        "",
        *_arms("def number : Pat → Nat", patterns, lambda item: str(item.number)),
        "",
        *_arms("def scaleOf : Pat → Scale", patterns, _scale_arm),
        "",
        *_smaller_edges(patterns),
        "",
        "theorem number_le (p : Pat) : number p ≤ patternNumberBound := by",
        "  cases p <;> decide",
        "",
        *_numeric_order(patterns),
        "",
        "def language : Language where",
        "  Pattern := Pat",
        "  scale := scaleOf",
        "  smaller q p := (q, p) ∈ smallerEdges",
        "  scale_mono := scaleMono_of_edges scaleOf smallerEdges (by decide)",
        "  acyclic := acyclicOfIncreasingNumber number patternNumberBound smallerEdges",
        "    number_le (by decide)",
        "",
        "instance : BEq language.Pattern := inferInstanceAs (BEq Pat)",
        "",
        "theorem numericOrder_ok : orderOk numericOrder smallerEdges = true := by",
        "  decide",
        "",
        "theorem numericOrder_valid : ValidSequence language numericOrder := by",
        "  intro q p h",
        "  exact (List.all_eq_true).mp numericOrder_ok (q, p) h",
        "",
        "end PatternLanguage.Instantiations.Buildings",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the building instantiation, or compare it under ``--check``."""
    parser = argparse.ArgumentParser(
        description="Render the seed catalog as a Lean building instantiation.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 when Buildings.lean differs from the render. Does not write.",
    )
    parser.add_argument(
        "root",
        nargs="?",
        type=Path,
        default=REPO_ROOT,
        help="Repository root. Defaults to the parent of scripts/.",
    )
    args = parser.parse_args(argv)
    try:
        catalog = load_catalog(args.root)
    except CatalogLoadError as exc:
        for error in exc.errors:
            print(error, file=sys.stderr)
        return 1
    if not catalog.ok:
        for link in catalog.missing_targets:
            print(
                f"missing target: {link.source} {link.field} {link.target}",
                file=sys.stderr,
            )
        return 1
    text = render(catalog)
    destination = args.root / BUILDINGS_RELATIVE
    if args.check:
        current = destination.read_text(encoding="utf-8") if destination.is_file() else None
        if current != text:
            print(STALE, file=sys.stderr)
            return 1
        return 0
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8")
    return 0


def _constructor(number: int) -> str:
    return f"p{number}"


def _inductive(patterns: tuple[Pattern, ...]) -> list[str]:
    if not patterns:
        return ["inductive Pat", "deriving DecidableEq, Repr, BEq"]
    lines = ["inductive Pat where"]
    lines.extend(f"  | {_constructor(pattern.number)}" for pattern in patterns)
    lines.append("deriving DecidableEq, Repr, BEq")
    return lines


def _arms(
    header: str,
    patterns: tuple[Pattern, ...],
    arm: Callable[[Pattern], str],
) -> list[str]:
    lines = [header]
    lines.extend(f"  | .{_constructor(pattern.number)} => {arm(pattern)}" for pattern in patterns)
    return lines


def _scale_arm(pattern: Pattern) -> str:
    if pattern.scale not in _SCALES:
        raise ValueError(f"unknown scale: {pattern.scale}")
    return f".{pattern.scale}"


def _smaller_edges(patterns: tuple[Pattern, ...]) -> list[str]:
    edges: list[str] = []
    for pattern in patterns:
        target = _constructor(pattern.number)
        edges.extend(
            f"  (.{_constructor(source)}, .{target})" for source in pattern.smaller
        )
    if not edges:
        return ["def smallerEdges : List (Pat × Pat) := []"]
    lines = ["def smallerEdges : List (Pat × Pat) := ["]
    for index, edge in enumerate(edges):
        suffix = "," if index < len(edges) - 1 else ""
        lines.append(f"{edge}{suffix}")
    lines.append("]")
    return lines


def _numeric_order(patterns: tuple[Pattern, ...]) -> list[str]:
    if not patterns:
        return ["def numericOrder : List Pat := []"]
    lines = ["def numericOrder : List Pat := ["]
    last = len(patterns) - 1
    for index, pattern in enumerate(patterns):
        suffix = "," if index < last else ""
        lines.append(f"  .{_constructor(pattern.number)}{suffix}")
    lines.append("]")
    return lines


if __name__ == "__main__":
    raise SystemExit(main())
